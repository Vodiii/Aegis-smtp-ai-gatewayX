def make_cases() -> tuple[list[dict], list[dict]]:
    benign: list[dict] = []
    cohorts = [OBVIOUS_BENIGN, CONTEXTUAL_BENIGN, SUSPICIOUS_BENIGN, OBFUSCATED_BENIGN]
    target_counts = [70, 35, 30, 15]
    i = 1
    for cohort, count in zip(cohorts, target_counts):
        for j in range(count):
            subject, body = cohort[j % len(cohort)]
            benign.append({
                "id": f"B{i:03d}",
                "category": "BENIGN",
                "subject": f"{subject} #{i}",
                "body": body,
                "cohort": cohort is SUSPICIOUS_BENIGN and "suspicious-benign" or "general",
            })
            i += 1

    threats: list[dict] = []
    tid = 1
    for category, templates in THREAT_TEMPLATES.items():
        for body in templates:
            threats.append({
                "id": f"T{tid:03d}",
                "category": category,
                "subject": "Предупреждение",
                "body": body,
            })
            tid += 1
    return benign, threats


def main() -> int:
    parser = argparse.ArgumentParser(description="Benchmark the cheap pre-AI risk gate")
    parser.add_argument("--training", default="config/risk_training.json")
    args = parser.parse_args()
    settings = GatewaySettings(risk_training_path=args.training)
    engine = RiskEngine(settings)
    benign, threats = make_cases()

    benign_bypassed = 0
    benign_to_ai = 0
    benign_cohorts: dict[str, list[int]] = {}
    threat_bypassed = 0
    threat_to_ai = 0
    threat_bypassed_by_category: dict[str, list[str]] = {}

    for case in benign:
        result = engine.assess(EmailDocument(subject=case["subject"], text=case["body"]))
        bucket = "FAST" if not result.requires_ai else "AI"
        cohort = str(case.get("cohort", "general"))
        counts = benign_cohorts.setdefault(cohort, [0, 0])
        counts[0 if bucket == "FAST" else 1] += 1
        if result.requires_ai:
            benign_to_ai += 1
        else:
            benign_bypassed += 1

    for case in threats:
        result = engine.assess(EmailDocument(subject=case["subject"], text=case["body"]))
        if result.requires_ai:
            threat_to_ai += 1
        else:
            threat_bypassed += 1
            threat_bypassed_by_category.setdefault(case["category"], []).append(case["id"])

    total = len(benign) + len(threats)
    total_bypassed = benign_bypassed
    print("Risk Gate Benchmark")
    print("=" * 72)
    print(f"Benign: {len(benign)}")
    print(f"  FAST bypass: {benign_bypassed} ({benign_bypassed/len(benign)*100:.1f}%)")
    print(f"  AI required: {benign_to_ai} ({benign_to_ai/len(benign)*100:.1f}%)")
    print("  Benign cohorts:")
    for cohort, (fast, ai) in benign_cohorts.items():
        total_cohort = fast + ai
        print(f"    {cohort}: FAST={fast} ({fast/total_cohort*100:.1f}%), AI={ai} ({ai/total_cohort*100:.1f}%)")
    print(f"Threats: {len(threats)}")
    print(f"  Sent to AI: {threat_to_ai} ({threat_to_ai/len(threats)*100:.1f}%)")
    print(f"  FAST bypass (danger): {threat_bypassed}")
    print(f"Total AI calls avoided in this benchmark: {total_bypassed}/{total} ({total_bypassed/total*100:.1f}% of all messages)")
    print(f"Approx. benign AI reduction: {benign_bypassed/len(benign)*100:.1f}%")
    if threat_bypassed_by_category:
        print("\nDANGER: threat cases bypassed the AI gate:")
        for category, ids in threat_bypassed_by_category.items():
            print(f"  {category}: {', '.join(ids)}")
        return 2
    print("\nGate safety check: PASS — 100% of synthetic threats reach AI.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
